const hash = (text) => {
  let h = 0;
  for (const ch of text) h = (h * 31 + ch.codePointAt(0)) >>> 0;
  return h;
};

export function pickMessage(kind, seed, values) {
  const list = MESSAGES[kind] || [];
  if (!list.length) return { title: '', body: '' };
  const template = list[hash(`${kind}|${seed}`) % list.length];
  const fill = (text) => text.replace(/\{(\w+)\}/g, (_, key) => (values[key] ?? '').toString());
  return { title: fill(template.title), body: fill(template.body) };
}
